/**
 * Fast lookup map for format ID -> FormatDefinition
 */
const FORMAT_ID_MAP = new Map<string, FormatDefinition>(
  FORMAT_CATALOG.map((fmt) => [fmt.id.toLowerCase(), fmt])
);

/**
 * Fast lookup map for extension -> FormatDefinition
 */
const FORMAT_EXT_MAP = new Map<string, FormatDefinition>();
for (const fmt of FORMAT_CATALOG) {
  for (const ext of fmt.extensions) {
    FORMAT_EXT_MAP.set(ext.toLowerCase(), fmt);
  }
}

/**
 * Get FormatDefinition by canonical format ID (case-insensitive).
 */
export function getFormatById(id: string): FormatDefinition | undefined {
  if (!id) return undefined;
  return FORMAT_ID_MAP.get(id.trim().toLowerCase());
}

/**
 * Get FormatDefinition by file extension or filename (case-insensitive).
 * Handles inputs like 'png', '.png', 'image.png', 'archive.tar.gz'.
 */
export function getFormatByExtension(extOrFilename: string): FormatDefinition | undefined {
  if (!extOrFilename) return undefined;
  let clean = extOrFilename.trim().toLowerCase();

  // Strip leading dot if present
  if (clean.startsWith('.')) {
    clean = clean.slice(1);
  }

  // If input contains filename or path, get extension after last dot (or last two dots for tar.gz)
  if (clean.includes('/')) {
    clean = clean.split('/').pop() || clean;
  }
  if (clean.includes('\\')) {
    clean = clean.split('\\').pop() || clean;
  }

  // Check double extension like tar.gz / tar.bz2 first
  if (clean.endsWith('.tar.gz') || clean.endsWith('.tgz')) {
    const doubleMatch = FORMAT_EXT_MAP.get('tgz') || FORMAT_EXT_MAP.get('tar.gz');
    if (doubleMatch) return doubleMatch;
  }

  // Extract trailing extension
  if (clean.includes('.')) {
    const parts = clean.split('.');
    clean = parts[parts.length - 1];
  }

  return FORMAT_EXT_MAP.get(clean);
}

/**
 * Get all formats in a specific category.
 */
export function getFormatsByCategory(category: FormatCategory): FormatDefinition[] {
  return FORMAT_CATALOG.filter((fmt) => fmt.category === category);
}
